/**
 * Generates src/scopes/generated/* from the installed dependencies.
 *
 * Why generate instead of `import * as lucide`: the wildcard import pulls all
 * 120 KB (brotli) of lucide into the bundle because Scope.ts spreads every
 * export, so nothing downstream can tree-shake it. Loading icons individually
 * costs ~0.7 KB each instead -- but only if every import specifier is a string
 * literal. A computed specifier (`import(\`.../${name}.js\`)`) is unanalyzable
 * by Vite and Rollup and fails at runtime there, so the literals have to exist
 * in the source, which means generating them.
 *
 * Two outputs, because a flat name -> loader map would repeat the same file
 * path for every alias (lucide exports ~5600 names for ~1900 files):
 *
 *   ICON_LOADERS   kebab file name -> () => import('<literal path>')
 *   ICON_ALIASES   PascalCase name -> kebab file name, ONLY where the name
 *                  cannot be derived mechanically
 *
 * Most names are derivable at runtime (`ActivityIcon` and `LucideActivity`
 * both reduce to `activity`), so the alias table only carries the genuine
 * renames like `SortDesc -> arrow-down-wide-narrow`.
 *
 * Also emits the recharts and motion export-name lists. Those two packages are
 * loaded whole (they are not per-component splittable the way icons are), so
 * all that is needed is a membership test cheap enough to run before deciding
 * whether to fetch them at all.
 *
 *   bun run scripts/generate-scope-maps.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = resolve(ROOT, "node_modules/lucide-react/dist/esm/lucide-react.js");
const OUT_DIR = resolve(ROOT, "src/scopes/generated");
const OUT = resolve(OUT_DIR, "lucideIconMap.ts");
const OUT_NAMES = resolve(OUT_DIR, "scopeNames.ts");

/** `PascalCase` -> `kebab-case`, matching how lucide names its icon files. */
export function toKebab(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

/**
 * lucide's ESM entry is one re-export per icon file, carrying every alias:
 *   export { default as SortDesc, default as LucideSortDesc, ... } from './icons/arrow-down-wide-narrow.js';
 * That is the only place the alias -> file relationship exists in the package.
 */
function parseEntry(source) {
  const re = /export \{([^}]*)\} from '\.\/icons\/([^']+)';/g;
  const nameToFile = new Map();
  const files = new Set();

  let match;
  while ((match = re.exec(source))) {
    const file = match[2].replace(/\.js$/, "");
    files.add(file);
    for (const part of match[1].split(",")) {
      const named = part.trim().match(/^default as (\w+)$/);
      if (named) nameToFile.set(named[1], file);
    }
  }
  return { nameToFile, files: [...files].sort() };
}

const { nameToFile, files } = parseEntry(readFileSync(ENTRY, "utf8"));
if (files.length === 0) {
  // The internal path or the entry format changed -- fail loudly rather than
  // emitting an empty map that would break every icon at runtime.
  throw new Error(`No icon re-exports found in ${ENTRY}. Did lucide-react change its build layout?`);
}

// Split the names: derivable ones cost nothing to ship, the rest need a row.
const aliases = [];
for (const [name, file] of nameToFile) {
  const base = name.replace(/Icon$/, "").replace(/^Lucide/, "");
  if (toKebab(base) !== file) aliases.push([name, file]);
}
aliases.sort(([a], [b]) => (a < b ? -1 : 1));

const banner = `// GENERATED by scripts/generate-lucide-icon-map.mjs -- do not edit.
// Source: lucide-react@${JSON.parse(readFileSync(resolve(ROOT, "node_modules/lucide-react/package.json"), "utf8")).version}
// ${files.length} icon files, ${nameToFile.size} exported names, ${aliases.length} needing an explicit alias.
`;

const loaders = files
  .map((f) => `  '${f}': () => import('lucide-react/dist/esm/icons/${f}.js'),`)
  .join("\n");

const aliasRows = aliases.map(([name, file]) => `  ${name}: '${file}',`).join("\n");

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `${banner}
/** kebab icon file -> dynamic import. Every specifier is a literal so Vite,
 * webpack and Rollup can all statically split it. */
export const ICON_LOADERS: Record<string, () => Promise<{ default: unknown }>> = {
${loaders}
}

/** Exported names that do NOT reduce to their file name mechanically. */
export const ICON_ALIASES: Record<string, string> = {
${aliasRows}
}

/** Every name lucide exports, for membership checks without loading anything. */
export const ICON_NAME_COUNT = ${nameToFile.size}
`,
);

console.log(
  `wrote ${OUT}\n  ${files.length} loaders, ${nameToFile.size} names, ${aliases.length} explicit aliases`,
);

// ---- recharts / motion name lists -----------------------------------------
// Read from the real modules rather than a hand-kept list, so the detection can
// never drift from what the scope would actually provide.
// A namespace object carries `default`, which is both a reserved word (so it
// cannot be a `new Function` parameter) and a word that appears in every
// `export default` -- leaving it in would make every component look like it
// used recharts. Drop anything that is not a plain identifier.
const isUsableName = (name) => /^[A-Za-z_$][\w$]*$/.test(name) && name !== "default";

const exportNames = async (mod) => Object.keys(await import(mod)).filter(isUsableName).sort();

const recharts = await exportNames("recharts");
const motion = await exportNames("motion/react");

const quoted = (names) => names.map((n) => `  '${n}',`).join("\n");

writeFileSync(
  OUT_NAMES,
  `// GENERATED by scripts/generate-scope-maps.mjs -- do not edit.

/** recharts exports. Referencing any of these pulls in ~138 KB, so the check
 * happens before the import, not after. */
export const RECHARTS_NAMES: string[] = [
${quoted(recharts)}
]

/** motion/react exports. \`motion\` itself is lowercase and is what <motion.div>
 * resolves against, so it is in this list too. */
export const MOTION_NAMES: string[] = [
${quoted(motion)}
]
`,
);

console.log(
  `wrote ${OUT_NAMES}\n  ${recharts.length} recharts names, ${motion.length} motion names`,
);
